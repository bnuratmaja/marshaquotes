create table if not exists public.marsha_fall_scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 1 and 12),
  score integer not null check (score >= 0 and score <= 999999),
  created_at timestamptz not null default now()
);

create index if not exists marsha_fall_scores_score_idx
  on public.marsha_fall_scores (score desc, created_at asc);

alter table public.marsha_fall_scores enable row level security;

drop policy if exists "public can read top scores" on public.marsha_fall_scores;
create policy "public can read top scores"
  on public.marsha_fall_scores
  for select
  using (true);
